defmodule Vega.Index do
  @moduledoc "Capability index. Run write/0 to regenerate /app/NOTES.md; available/0 reports loaded modules."
  @entries [
    {Vega.Files, "Files and shell", "Vega.Files.read(\"/app/NOTES.md\"); Vega.Files.sh(\"git status\")"},
    {Vega.Delegation, "Delegation", "See docs/delegation.md and Vega.Delegation module docs"},
    {Vega.Compaction, "Automatic compaction", "See docs/compaction.md; runs before each model request"},
    {Vega.Tasks, "Background shell tasks", "See docs/background-tasks.md and Vega.Tasks module docs"},
    {Vega.Goals, "Durable goals", "See docs/goals.md and Vega.Goals module docs"},
    {Vega.Memory, "Durable identity memory", "See Vega.Memory module docs"},
    {Vega.Web, "Readable web pages", "See docs/web-access.md and Vega.Web module docs"},
    {Vega.Search, "Exa search and research", "See docs/search.md and Vega.Search module docs"},
    {Vega.MCP, "MCP servers and events", "See docs/mcp.md and Vega.MCP module docs"},
    {Vega.Images, "Vision attachments", "See docs/images.md and Vega.Images module docs"},
    {Vega.Bots, "Consumer chat", "Visit /bots; see docs/bots.md"}
  ]
  def entries, do: @entries
  def available, do: Enum.map(@entries, fn {m, label, _} -> {m, label, Code.ensure_loaded?(m)} end)
  def write(path \\ "/app/NOTES.md") do
    text = "# Vega's seedling capability index\n\nWork lives on `seedling/vega-*`, never main. This index is generated by `Vega.Index.write/0`.\nLibraries compose through eval; consult module docs for exact return shapes and limits.\n\n" <>
      Enum.map_join(@entries, "\n", fn {m, label, use} -> "- **#{label}** (`#{inspect(m)}`): #{use}." end) <>
      "\n\nIntegration status, real test evidence and known limitations: [docs/vega-status.md](docs/vega-status.md).\nAPI keys are node settings (`Nano.Settings.get/1`), never source or logs.\nThe operator dashboard remains at `/`; consumer chat is separate.\n"
    Vega.Files.write(path, text)
  end
end
