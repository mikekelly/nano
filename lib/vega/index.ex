defmodule Vega.Index do
  @moduledoc "Capability index. Run write/0 to regenerate /app/NOTES.md; available/0 reports loaded modules."
  @entries [
    {Vega.Files, "Files and shell",
     "Vega.Files.read(\"/app/NOTES.md\"); Vega.Files.sh(\"git status\")"},
    {Vega.Delegation, "Delegation",
     "See docs/vega-delegation.md and Vega.Delegation module docs"},
    {Vega.Compaction, "Automatic compaction",
     "See docs/vega-compaction.md; runs before each model request"},
    {Vega.Tasks, "Background shell tasks",
     "See docs/vega-background-tasks.md and Vega.Tasks module docs"},
    {Vega.Goals, "Durable goals", "See docs/vega-goals-memory.md and Vega.Goals module docs"},
    {Vega.Memory, "Durable identity memory", "See Vega.Memory module docs"},
    {Vega.Decision, "Typed cheap judgments (Jev)",
     "See docs/vega-decision.md; exact setting TYPESAFE_API_KEY"},
    {Vega.Browser, "Stateful CDP browser",
     "See docs/vega-browser.md; Lightpanda screenshots are text-layout, not CSS"},
    {Vega.Web, "Readable web pages", "See docs/vega-web-search.md and Vega.Web module docs"},
    {Vega.Search, "Exa search and research",
     "See docs/vega-web-search.md and Vega.Search module docs"},
    {Vega.MCP, "MCP servers and events", "See docs/vega-mcp.md and Vega.MCP module docs"},
    {Vega.Images, "Vision attachments", "See docs/vega-images.md and Vega.Images module docs"},
    {Vega.Bots, "Consumer chat", "Visit /bots; see docs/bots.md"}
  ]
  def entries, do: @entries

  def available,
    do: Enum.map(@entries, fn {m, label, _} -> {m, label, Code.ensure_loaded?(m)} end)

  def write(path \\ "/app/NOTES.md") do
    text =
      "# Vega's seedling capability index\n\nWork lives on `seedling/vega-*`, never main. This index is generated by `Vega.Index.write/0`.\nLibraries compose through eval; consult module docs for exact return shapes and limits.\n\n" <>
        Enum.map_join(@entries, "\n", fn {m, label, use} ->
          "- **#{label}** (`#{inspect(m)}`): #{use}."
        end) <>
        "\n\nIntegration status, real test evidence and known limitations: [docs/vega-status.md](docs/vega-status.md).\nAPI keys are node settings (`Nano.Settings.get/1`), never source or logs.\nThe operator dashboard remains at `/`; consumer chat is separate.\n"

    Vega.Files.write(path, text)
  end
end
